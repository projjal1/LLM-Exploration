"""
02: LLM-as-a-Judge (Reference-Based Factual Correctness)
=======================================================

Concept:
--------
When an exact string match is too brittle because answers can be phrased
in many valid ways, we use an LLM as an impartial Judge.

In reference-based evals, the judge is provided:
1. The User Question / Prompt
2. The Reference Answer (Ground Truth)
3. The Candidate Model Answer (to be evaluated)

The judge evaluates semantic equivalence, completeness, and detects hallucinations.

Key Techniques:
- Structured Output via Pydantic: Guarantees the judge outputs an explanation,
  a 1-5 Likert score, and a boolean verdict.
- Zero-temperature judge: Minimizes variance across evaluation runs.
"""

from typing import List
from pydantic import BaseModel, Field
from langchain_ollama import ChatOllama
from langchain_core.prompts import ChatPromptTemplate


# ---------------------------------------------------------------------------
# 1. Models & Structured Evaluation Schema
# ---------------------------------------------------------------------------

generator_llm = ChatOllama(model="qwen3:8b", temperature=0.3)
judge_llm = ChatOllama(model="qwen3:8b", temperature=0.0)


class FactualCorrectnessReport(BaseModel):
    """Structured evaluation report generated by the LLM Judge."""
    reasoning: str = Field(
        description="Step-by-step reasoning comparing claims in the candidate answer against the reference answer."
    )
    score: int = Field(
        ge=1,
        le=5,
        description="Factual accuracy score: 1=completely false/hallucinated, 3=partially correct, 5=completely accurate."
    )
    unsupported_claims: List[str] = Field(
        default_factory=list,
        description="Any claims made by the candidate that are not supported or contradicted by the reference."
    )
    is_correct: bool = Field(
        description="True if the candidate answer is factually correct and aligned with the reference."
    )


# ---------------------------------------------------------------------------
# 2. Judge Prompt & Chain
# ---------------------------------------------------------------------------

JUDGE_PROMPT = ChatPromptTemplate.from_messages([
    (
        "system",
        "You are an impartial, expert evaluation judge assessing factual correctness.\n"
        "Your task is to determine whether the Candidate Answer accurately conveys the facts "
        "present in the Reference Ground Truth.\n\n"
        "Guidelines:\n"
        "- Do not penalize phrasing differences, synonyms, or tone if the core facts are accurate.\n"
        "- Penalize factual contradictions, false claims, and severe omissions.\n"
        "- Produce your response strictly conforming to the requested schema."
    ),
    (
        "user",
        "Input Question:\n{question}\n\n"
        "Reference Answer (Ground Truth):\n{reference}\n\n"
        "Candidate Answer:\n{candidate_answer}\n\n"
        "Evaluate the candidate answer."
    )
])

# Bind the Pydantic schema to the judge for structured output
judge_chain = JUDGE_PROMPT | judge_llm.with_structured_output(FactualCorrectnessReport)


def evaluate_response(question: str, reference: str, candidate_answer: str) -> FactualCorrectnessReport:
    """Executes the reference-based judge evaluation."""
    return judge_chain.invoke({
        "question": question,
        "reference": reference,
        "candidate_answer": candidate_answer,
    })


# ---------------------------------------------------------------------------
# 3. Demonstration Runs
# ---------------------------------------------------------------------------

def main():
    print("=" * 75)
    print("⚖️ RUNNING LLM-AS-A-JUDGE (REFERENCE-BASED EVALS)")
    print("=" * 75)

    test_scenarios = [
        {
            "scenario": "Live Generation vs Reference",
            "question": "What causes the aurora borealis (Northern Lights)?",
            "reference": (
                "The aurora borealis is caused by charged particles from the solar wind "
                "colliding with gaseous particles (oxygen and nitrogen) in Earth's atmosphere, "
                "guided by Earth's magnetic field."
            ),
            "candidate_override": None,  # Will be generated live by generator_llm
        },
        {
            "scenario": "Synthetic Hallucinated Answer (Failure Case)",
            "question": "Who discovered penicillin and in what year?",
            "reference": "Alexander Fleming discovered penicillin in September 1928.",
            "candidate_override": (
                "Penicillin was discovered by Louis Pasteur in 1885 while studying rabies in Paris."
            ),
        },
        {
            "scenario": "Alternative Phrasing (Pass Case)",
            "question": "What is the capital of Australia?",
            "reference": "The federal capital city of Australia is Canberra.",
            "candidate_override": "Canberra serves as the capital of the Commonwealth of Australia.",
        }
    ]

    for idx, item in enumerate(test_scenarios, start=1):
        print(f"\n[Test Case {idx}] {item['scenario']}")
        print(f"Question:  {item['question']}")
        print(f"Reference: {item['reference']}")

        if item["candidate_override"]:
            candidate = item["candidate_override"]
            print(f"Candidate (Pre-canned): {candidate}")
        else:
            print("Generating response with qwen3:8b...")
            candidate = generator_llm.invoke(item["question"]).content.strip()
            print(f"Candidate (Live LLM): {candidate}")

        print("\nEvaluating with Judge...")
        eval_report: FactualCorrectnessReport = evaluate_response(
            question=item["question"],
            reference=item["reference"],
            candidate_answer=candidate,
        )

        status = "✅ PASS" if eval_report.is_correct else "❌ FAIL"
        print(f"Result:       {status} (Score: {eval_report.score}/5)")
        print(f"Reasoning:    {eval_report.reasoning}")
        if eval_report.unsupported_claims:
            print(f"Unsupported:  {eval_report.unsupported_claims}")
        print("-" * 75)


if __name__ == "__main__":
    main()
